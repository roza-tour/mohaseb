// رابط التطبيق الموحَّد: Link من Next بلا تحميل مسبق تلقائي.
//
// Link يحمّل مسبقاً كل رابط يظهر على الشاشة. صفحات البرنامج كلها ديناميكية
// (تقرأ الجلسة وقاعدة البيانات)، فكل رابط ظاهر = طلب كامل للسيرفر. فتح الصفحة
// الرئيسية كان يطلق 51 طلباً منها (القائمة الجانبية وروابط الرحلات)، يتكرر
// بعضها، فتقف ضغطة المستخدم الحقيقية في طابور خلفها — والاستضافة المشتركة
// تشغّل التطبيق بعملية واحدة تقريباً. القياس: من 1.1–2.5 ثانية لكل ضغطة.
//
// الافتراضي هنا prefetch={false} (لا عند الظهور ولا عند المرور بالمؤشر)،
// والإحساس بالاستجابة يأتي من شريط التقدّم أعلى الصفحة (NavProgress) ومن
// loading.tsx. ويمكن تمرير prefetch صراحةً لرابط بعينه عند الحاجة.
import Link from "next/link";
import type { ComponentProps } from "react";

export default function AppLink({ prefetch, ...props }: ComponentProps<typeof Link>) {
  return <Link prefetch={prefetch ?? false} {...props} />;
}
